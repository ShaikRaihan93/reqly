-- Local accounts, persistent sign-in sessions, and an owner on every piece of user data.
-- Existing rows keep owner_id NULL until the first account is created, which claims them.

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name CHARACTER VARYING(255) NOT NULL,
    email CHARACTER VARYING(255) NOT NULL,
    password_hash CHARACTER VARYING(255) NOT NULL,
    created_at TIMESTAMP(6),
    last_login_at TIMESTAMP(6),
    CONSTRAINT uk_app_users_email UNIQUE (email)
);

CREATE TABLE auth_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash CHARACTER VARYING(64) NOT NULL,
    user_id BIGINT NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6),
    CONSTRAINT uk_auth_sessions_token UNIQUE (token_hash),
    CONSTRAINT fk_sessions_user FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE
);

ALTER TABLE collections ADD COLUMN owner_id BIGINT;
ALTER TABLE collections ADD CONSTRAINT fk_collections_owner FOREIGN KEY (owner_id) REFERENCES app_users (id);
CREATE INDEX idx_collections_owner ON collections (owner_id);

ALTER TABLE api_requests ADD COLUMN owner_id BIGINT;
ALTER TABLE api_requests ADD CONSTRAINT fk_requests_owner FOREIGN KEY (owner_id) REFERENCES app_users (id);
CREATE INDEX idx_requests_owner ON api_requests (owner_id);

ALTER TABLE environments ADD COLUMN owner_id BIGINT;
ALTER TABLE environments ADD CONSTRAINT fk_environments_owner FOREIGN KEY (owner_id) REFERENCES app_users (id);
CREATE INDEX idx_environments_owner ON environments (owner_id);

ALTER TABLE request_history ADD COLUMN owner_id BIGINT;
ALTER TABLE request_history ADD CONSTRAINT fk_history_owner FOREIGN KEY (owner_id) REFERENCES app_users (id);
CREATE INDEX idx_history_owner_time ON request_history (owner_id, executed_at);
