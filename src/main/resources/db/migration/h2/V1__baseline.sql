-- Schema as of Reqly 1.0 before accounts existed (generated from a real database, then tidied).
-- Existing installations are baselined at this version, so this only runs on new databases.

CREATE TABLE environments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    name CHARACTER VARYING(255) NOT NULL,
    updated_at TIMESTAMP(6),
    variables CHARACTER VARYING,
    secrets CHARACTER VARYING
);

CREATE TABLE collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    description CHARACTER VARYING(255),
    name CHARACTER VARYING(255) NOT NULL,
    sort_order INTEGER,
    updated_at TIMESTAMP(6),
    parent_id BIGINT,
    CONSTRAINT fk_collections_parent FOREIGN KEY (parent_id) REFERENCES collections (id)
);

CREATE TABLE api_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_config CHARACTER VARYING,
    auth_type CHARACTER VARYING(255),
    body CHARACTER VARYING,
    body_type CHARACTER VARYING(255),
    created_at TIMESTAMP(6),
    headers CHARACTER VARYING,
    method CHARACTER VARYING(255) NOT NULL,
    name CHARACTER VARYING(255) NOT NULL,
    params CHARACTER VARYING,
    pre_request_script CHARACTER VARYING,
    sort_order INTEGER,
    test_script CHARACTER VARYING,
    updated_at TIMESTAMP(6),
    url CHARACTER VARYING(2048) NOT NULL,
    collection_id BIGINT,
    environment_id BIGINT,
    disabled_items CHARACTER VARYING,
    settings CHARACTER VARYING,
    post_response_script CHARACTER VARYING,
    CONSTRAINT fk_requests_collection FOREIGN KEY (collection_id) REFERENCES collections (id),
    CONSTRAINT fk_requests_environment FOREIGN KEY (environment_id) REFERENCES environments (id)
);

CREATE TABLE request_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    executed_at TIMESTAMP(6),
    method CHARACTER VARYING(255) NOT NULL,
    request_body CHARACTER VARYING,
    request_headers CHARACTER VARYING,
    response_body CHARACTER VARYING,
    response_headers CHARACTER VARYING,
    response_size_bytes BIGINT,
    response_time_ms BIGINT,
    status_code INTEGER,
    test_results CHARACTER VARYING,
    url CHARACTER VARYING(2048) NOT NULL,
    request_id BIGINT,
    CONSTRAINT fk_history_request FOREIGN KEY (request_id) REFERENCES api_requests (id)
);
